"""Local-only operator clip handoff to the actual approved MP4 renderer.

Original synthetic test video generated by FFmpeg; no human material,
provider APIs, paid requests, database schema change or public upload.
"""
from __future__ import annotations

import ast
import json
from pathlib import Path
import shutil

import pytest

from drama_factory.pipeline.local_shot_media import (
    LocalShotMediaError, get_staged_shot_clips, stage_local_shot_video,
)
from drama_factory.pipeline.offline_render import render_approved_preview, inspect_mp4
from drama_factory.pipeline.offline_review import load_local_offline_review
from test_media_ingest import make_source, make_ready_run


requires_ffmpeg = pytest.mark.skipif(
    shutil.which("ffmpeg") is None or shutil.which("ffprobe") is None,
    reason="Local FFmpeg + FFprobe are required",
)


def _context(client, tmp_path):
    run = make_ready_run(client)
    db = client.app.state.db
    series = db.one(
        """SELECT e.project_id FROM productions p
           JOIN episodes e ON e.id=p.episode_id WHERE p.id=?""", (run,),
    )["project_id"]
    root = tmp_path / "local-shot-media"
    return db, series, run, root


def _stage(db, series, run, root, file, *, shot="S1", rights=True):
    return stage_local_shot_video(
        db, run, series, root, shot_id=shot, filename=file.name,
        content=file.read_bytes(), operator_attests_rights=rights,
    )


@requires_ffmpeg
def test_local_video_registry_and_render_two_shot_mixed_mp4(client, tmp_path):
    db, series, run, root = _context(client, tmp_path)
    source = make_source(tmp_path / "original.mp4", duration=2)
    receipt = _stage(db, series, run, root, source)
    assert receipt["shot_id"] == "S1"
    assert receipt["paid_api_calls"] == 0
    assert receipt["rights_self_attested"] is True
    assert receipt["rights_independently_verified"] is False
    assert len(receipt["sha256"]) == 64
    clips = get_staged_shot_clips(db, run, series, root)
    assert list(clips) == ["S1"]
    assert clips["S1"].is_file()
    assert clips["S1"].parent == root / series / run
    manifest = render_approved_preview(
        db, run, tmp_path / "rendered", source_clips=clips,
    )
    assert [shot["media_source"] for shot in manifest["shots"]] == [
        "provided_local_clip", "placeholder",
    ]
    assert manifest["supplied_local_clips"] == 1
    assert manifest["placeholder_visuals"] is True
    assert manifest["paid_api_calls"] == 0
    assert inspect_mp4(Path(manifest["mp4_path"]), 4)["subtitle_codec"] == "mov_text"
    report = load_local_offline_review(
        db, run, tmp_path / "rendered", series_id=series,
    )
    assert report["actual_local_media_clips"] == 1
    assert report["technical_qa_passed"] is True
    assert report["publish_approved"] is False
    assert report["commercial_rights_verified"] is False


@requires_ffmpeg
def test_reopening_same_production_recovers_registered_source(client, tmp_path):
    db, series, run, root = _context(client, tmp_path)
    source = make_source(tmp_path / "original.mp4")
    first = _stage(db, series, run, root, source)
    second = _stage(db, series, run, root, source)
    assert first["sha256"] == second["sha256"]
    assert get_staged_shot_clips(db, run, series, root)["S1"].is_file()


@requires_ffmpeg
def test_explicit_replacement_rebinds_only_chosen_shot(client, tmp_path):
    db, series, run, root = _context(client, tmp_path)
    a = make_source(tmp_path / "first.mp4", pattern="testsrc2")
    b = make_source(tmp_path / "second.mp4", pattern="smptebars")
    _stage(db, series, run, root, a)
    _stage(db, series, run, root, a, shot="S2")
    original = get_staged_shot_clips(db, run, series, root)
    original_s2 = original["S2"]
    _stage(db, series, run, root, b, shot="S1")
    revised = get_staged_shot_clips(db, run, series, root)
    assert revised["S1"] != original["S1"]
    assert revised["S2"] == original_s2
    assert original["S1"].exists()  # append-only content; receipt rebind only.


@requires_ffmpeg
def test_invalid_or_unapproved_uploads_do_not_persist_receipts(client, tmp_path):
    db, series, run, root = _context(client, tmp_path)
    source = make_source(tmp_path / "shot.mp4")
    with pytest.raises(LocalShotMediaError, match="attestation"):
        _stage(db, series, run, root, source, rights=False)
    with pytest.raises(LocalShotMediaError, match="Selected shot"):
        _stage(db, series, run, root, source, shot="unknown")
    with pytest.raises(LocalShotMediaError, match="extension"):
        stage_local_shot_video(
            db, run, series, root, shot_id="S1", filename="bad.txt",
            content=source.read_bytes(), operator_attests_rights=True,
        )
    with pytest.raises(LocalShotMediaError):
        stage_local_shot_video(
            db, run, series, root, shot_id="S1", filename="fake.mp4",
            content=b"not a movie" * 200, operator_attests_rights=True,
        )
    assert get_staged_shot_clips(db, run, series, root) == {}


@requires_ffmpeg
def test_scope_refuses_other_series_and_preapproval_even_for_correct_bytes(client, tmp_path):
    db, series, run, root = _context(client, tmp_path)
    source = make_source(tmp_path / "shot.mp4")
    other = client.post("/api/v1/projects", json={
        "title": "Other series", "premise": "No cross-media",
    }).json()["series_id"]
    with pytest.raises(LocalShotMediaError, match="Production must belong"):
        _stage(db, other, run, root, source)
    with pytest.raises(LocalShotMediaError):
        get_staged_shot_clips(db, run, other, root)
    # No further upload permitted while either original human gate is pending.
    db.exec("UPDATE productions SET status=? WHERE id=?", ("script_review_pending", run))
    with pytest.raises(LocalShotMediaError, match="both approvals"):
        _stage(db, series, run, root, source)
    assert not root.exists()


@requires_ffmpeg
def test_corrupt_or_deleted_content_refuses_all_staged_shots(client, tmp_path):
    db, series, run, root = _context(client, tmp_path)
    source = make_source(tmp_path / "shot.mp4")
    _stage(db, series, run, root, source)
    staged = get_staged_shot_clips(db, run, series, root)
    staged["S1"].write_bytes(b"tampered video")
    with pytest.raises(LocalShotMediaError, match="integrity"):
        get_staged_shot_clips(db, run, series, root)
    with pytest.raises(LocalShotMediaError, match="Conflicting"):
        _stage(db, series, run, root, source)


@requires_ffmpeg
def test_symlinked_receipt_media_and_root_are_rejected(client, tmp_path):
    db, series, run, root = _context(client, tmp_path)
    source = make_source(tmp_path / "shot.mp4")
    _stage(db, series, run, root, source)
    owned = root / series / run
    receipt = next(owned.glob("shot_*.json"))
    original = receipt.read_bytes()
    receipt.unlink()
    receipt.symlink_to(source)
    try:
        with pytest.raises(LocalShotMediaError, match="Untrusted"):
            get_staged_shot_clips(db, run, series, root)
        with pytest.raises(LocalShotMediaError, match="Linked"):
            _stage(db, series, run, root, source)
    finally:
        receipt.unlink()
        receipt.write_bytes(original)
    live = get_staged_shot_clips(db, run, series, root)
    assert live["S1"].is_file()
    link_root = tmp_path / "linked-root"
    link_root.symlink_to(root, target_is_directory=True)
    with pytest.raises(LocalShotMediaError, match="Linked"):
        get_staged_shot_clips(db, run, series, link_root)


@requires_ffmpeg
def test_integrity_refuses_modified_receipt_and_scope_swap(client, tmp_path):
    db, series, run, root = _context(client, tmp_path)
    source = make_source(tmp_path / "shot.mp4")
    _stage(db, series, run, root, source)
    receipt = next((root / series / run).glob("shot_*.json"))
    original = receipt.read_bytes()
    try:
        doc = json.loads(original)
        doc["production_id"] = "run_" + "0" * 14
        receipt.write_text(json.dumps(doc), encoding="utf-8")
        with pytest.raises(LocalShotMediaError, match="integrity"):
            get_staged_shot_clips(db, run, series, root)
    finally:
        receipt.write_bytes(original)
    assert "S1" in get_staged_shot_clips(db, run, series, root)


