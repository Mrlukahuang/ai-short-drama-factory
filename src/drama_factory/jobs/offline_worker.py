"""Run reviewed productions through independent, zero-API Fake shot workers.

This is a bounded local integration worker, not a scheduler daemon and NOT
Google Omni video generation. Its media are generated by FFmpeg/Pillow only.
"""
from __future__ import annotations

import hashlib
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from drama_factory.db import Database
from drama_factory.jobs.shots import (
    ShotJobError, claim_next_job, complete_fake_clip_job, prepare_shot_jobs,
    record_failure,
)
from drama_factory.pipeline.offline_render import render_approved_preview


class OfflineWorkerError(RuntimeError):
    pass


def run_offline_production(
    db: Database, production_id: str, media_root: Path,
    *, worker_id: str = "offline-worker",
    store_root: Path | None = None,
) -> dict:
    """One production; claiming and processing never leaves its series boundary."""
    jobs = prepare_shot_jobs(
        db, production_id, provider="fake",
        max_acknowledged_spend_usd="1.00", max_attempts=2,
    )
    active = [job for job in jobs if job["status"] != "succeeded"]
    if any(job["status"] != "pending" for job in active):
        raise OfflineWorkerError("Production has unsettled jobs requiring manual review")
    leased = []
    for _ in active:
        claimed = claim_next_job(
            db, worker_id, production_id=production_id, lease_seconds=900,
        )
        if claimed is None:
            raise OfflineWorkerError("Failed to claim all production jobs")
        leased.append(claimed)
    try:
        manifest = render_approved_preview(db, production_id, Path(media_root))
        work = Path(manifest["mp4_path"]).parent
        rendered = {shot["shot_id"]: shot for shot in manifest["shots"]}
        for job in leased:
            details = rendered.get(job["shot_id"])
            if details is None:
                raise OfflineWorkerError("Rendered clip missing for the claimed shot")
            clip = work / "clips" / details["clip_name"]
            complete_fake_clip_job(
                db, job["id"], worker_id=worker_id, clip_path=clip,
            )
        for job in jobs:
            if job["status"] != "succeeded":
                continue
            details = rendered[job["shot_id"]]
            clip = work / "clips" / details["clip_name"]
            if not clip.is_file():
                raise OfflineWorkerError("Previously completed media is missing")
            if hashlib.sha256(clip.read_bytes()).hexdigest() != job["result_sha256"]:
                raise OfflineWorkerError("Previously completed shot media changed")
    except Exception as exc:
        for job in leased:
            current = db.one("SELECT status FROM shot_jobs WHERE id=?", (job["id"],))
            if current and current["status"] == "leased":
                record_failure(
                    db, job["id"], f"Offline renderer failed: {type(exc).__name__}",
                    worker_id=worker_id,
                )
        raise

    rows = db.many(
        "SELECT * FROM shot_jobs WHERE production_id=? ORDER BY shot_id",
        (production_id,),
    )
    if not rows or any(job["status"] != "succeeded" for job in rows):
        raise OfflineWorkerError("Some offline shots did not complete")
    published = []
    if store_root is not None:
        from drama_factory.storage.artifacts import (
            publish_episode_preview, publish_shot_video,
        )
        for job in rows:
            published.append(
                publish_shot_video(db, job["id"], media_root, store_root)["id"]
            )
        published.append(
            publish_episode_preview(db, production_id, media_root, store_root)["id"]
        )
    return {
        "published_artifact_ids": published,
        "production_id": production_id,
        "series_id": manifest["series_id"],
        "shot_job_count": len(rows),
        "succeeded": len(rows),
        "mp4_path": manifest["mp4_path"],
        "mp4_sha256": manifest["mp4_sha256"],
        "shots_cached": sum(1 for s in manifest["shots"] if s["cached"]),
        "paid_provider_calls": 0,
        "real_ai_video": False,
    }


def run_offline_multi_series(
    db: Database, production_ids: list[str], media_root: Path,
    *, max_workers: int = 2,
    store_root: Path | None = None,
) -> list[dict]:
    """Bounded multi-series execution with SQLite-atomic claims.

    Running two different productions is supported, but duplicate IDs are
    rejected, not submitted twice. An individual failure stays in its series.
    """
    if not 1 <= max_workers <= 4:
        raise OfflineWorkerError("max_workers must be 1..4")
    if not production_ids or len(production_ids) != len(set(production_ids)):
        raise OfflineWorkerError("Production IDs must be nonempty and unique")
    if len(production_ids) > 10:
        raise OfflineWorkerError("Offline batch accepts at most 10 productions")
    root = Path(media_root)
    with ThreadPoolExecutor(max_workers=max_workers) as pool:
        futures = [
            pool.submit(
                run_offline_production, db, run_id, root,
                worker_id=f"offline_worker_{index:02d}",
                store_root=store_root,
            )
            for index, run_id in enumerate(production_ids)
        ]
        # Keep results in submitted order; failures never cause automatic
        # retry or hidden charges in another production.
        return [future.result() for future in futures]
