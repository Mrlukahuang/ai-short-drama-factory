"""Download-only recovery of an already-generated Google video into one shot job.

This module deliberately has NO call to interactions.create/generate. It requires an
existing reviewed, budget-gated, submitted Google shot task. Human-bound file IDs,
transactional download locks and hash verification prevent mixing series or replaying
a different provider result. Never expose these helpers through an unauthenticated API.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from drama_factory.db import Database, timestamp
from drama_factory.jobs.shots import ShotJobError, _event, complete_submitted_job
from drama_factory.models import EpisodeDraft
from drama_factory.pipeline.media_ingest import inspect_source
from drama_factory.pipeline.offline_render import render_approved_preview
from drama_factory.providers.google_omni_video import (
    GoogleOmniVideoProvider, google_video_download_uri,
)


class ExistingVideoRecoveryError(ShotJobError):
    pass


def _job_and_file(conn, job_id: str):
    return conn.execute(
        """SELECT j.*, g.file_id,g.recovery_active,g.bound_at
           FROM shot_jobs j LEFT JOIN google_existing_files g ON g.job_id=j.id
           WHERE j.id=?""", (job_id,),
    ).fetchone()


def _eligible(row):
    if row is None or row["provider"] != "google":
        raise ExistingVideoRecoveryError("Only an existing Google shot job can be recovered")
    if (
        row["model_id"] != "gemini-omni-1.1-flash"
        or not row["generation_intent_recorded"] or not row["provider_task_id"]
    ):
        raise ExistingVideoRecoveryError("Existing reviewed model submission/task ID required")
    if row["status"] not in ("submitted", "succeeded"):
        raise ExistingVideoRecoveryError("Job must be submitted or already succeeded")


def bind_existing_google_file(
    db: Database, job_id: str, file_id: str, *, operator_reviewed: bool = False,
) -> dict:
    """Immutable explicit binding: provider file ID belongs to this paid job.

    No new generation, no implicit association based on matching filenames.
    """
    if operator_reviewed is not True:
        raise ExistingVideoRecoveryError("Explicit operator review required")
    google_video_download_uri(file_id)  # Checks exact safe Google Files ID shape.
    with db.connection() as conn:
        conn.execute("BEGIN IMMEDIATE")
        row = _job_and_file(conn, job_id)
        _eligible(row)
        if row["file_id"] is not None:
            if row["file_id"] != file_id:
                raise ExistingVideoRecoveryError("Google file ID binding is immutable")
            return dict(row)
        if row["status"] != "submitted":
            raise ExistingVideoRecoveryError(
                "A completed job cannot be retroactively bound to a new file"
            )
        conn.execute(
            """INSERT INTO google_existing_files
               (job_id,file_id,recovery_active,bound_at)
               VALUES (?,?,0,?)""", (job_id, file_id, timestamp()),
        )
        _event(conn, job_id, "existing_google_file_bound",
               row["status"], row["status"],
               {"file_id": file_id, "new_model_generation_calls": 0,
                "operator_reviewed": True})
        return dict(_job_and_file(conn, job_id))


def _duration(conn, row) -> int:
    episode = conn.execute(
        "SELECT body_json,project_id FROM episodes WHERE id=?",
        (row["episode_id"],),
    ).fetchone()
    if episode is None or episode["project_id"] != row["series_id"]:
        raise ExistingVideoRecoveryError("Episode or series mismatch")
    draft = EpisodeDraft.model_validate_json(episode["body_json"])
    shot = next((s for s in draft.shots if s.shot_id == row["shot_id"]), None)
    if shot is None or shot.video_model != row["model_id"]:
        raise ExistingVideoRecoveryError("Shot/model no longer matches job")
    return shot.duration_seconds


def _location(root: Path, row) -> Path:
    # IDs are generated by our own DB; require safe components even if DB altered.
    import re
    for key in ("series_id", "production_id", "id"):
        if not re.fullmatch(r"[A-Za-z0-9_-]{3,100}", row[key]):
            raise ExistingVideoRecoveryError("Unsafe job path component")
    root_path = Path(root).resolve()
    return root_path / row["series_id"] / row["production_id"] / row["id"] / "source.mp4"


def _inspect_trusted(path: Path, seconds: int, *, expected_sha: str | None = None):
    if path.is_symlink() or not path.is_file():
        raise ExistingVideoRecoveryError("Recovered media missing or a symlink")
    source = inspect_source(path, seconds)
    if expected_sha is not None and source["sha256"] != expected_sha:
        raise ExistingVideoRecoveryError("Recovered media SHA256 mismatch")
    return source


def recover_existing_google_shot(
    db: Database, job_id: str, media_root: Path, *, operator_reviewed: bool = False,
    provider: GoogleOmniVideoProvider | None = None,
) -> dict:
    """Fetch an existing Google Files result only; no model generation ever.

    If a prior worker downloaded the MP4 but crashed before recording success,
    reuse the verified file rather than contacting Google again.
    """
    if operator_reviewed is not True:
        raise ExistingVideoRecoveryError("Explicit operator review required")
    with db.connection() as conn:
        conn.execute("BEGIN IMMEDIATE")
        row = _job_and_file(conn, job_id)
        _eligible(row)
        if row["file_id"] is None:
            raise ExistingVideoRecoveryError("Bind the existing Google file ID first")
        seconds = _duration(conn, row)
        dest = _location(media_root, row)
        if row["status"] == "succeeded":
            if Path(row["result_path"]).resolve() != dest:
                raise ExistingVideoRecoveryError("Recorded media outside job storage")
            info = _inspect_trusted(dest, seconds, expected_sha=row["result_sha256"])
            return {
                "job_id": job_id, "series_id": row["series_id"],
                "file_id": row["file_id"], "mp4_path": str(dest),
                "source_sha256": info["sha256"], "cached": True,
                "new_model_generation_calls": 0,
                "vendor_charge_usd": None,
            }
        if row["recovery_active"]:
            raise ExistingVideoRecoveryError("Recovery already active; manual unlock if worker crashed")
        conn.execute(
            "UPDATE google_existing_files SET recovery_active=1 WHERE job_id=?",
            (job_id,),
        )
        _event(conn, job_id, "existing_google_download_claimed",
               "submitted", "submitted", {"new_model_generation_calls": 0})

    try:
        # The downloadable file path is derived only from the job's DB scope.
        dest.parent.mkdir(parents=True, exist_ok=True)
        if dest.is_symlink():
            raise ExistingVideoRecoveryError("Refusing a linked output path")
        if dest.exists():
            # Resume from disk following a crash after download but before DB commit.
            info = _inspect_trusted(dest, seconds)
        else:
            selected = provider if provider is not None else GoogleOmniVideoProvider()
            receipt = selected.recover_existing(
                row["file_id"], dest, operator_approved=True,
                min_duration_seconds=seconds,
            )
            if (
                not isinstance(receipt, dict)
                or receipt.get("model_calls") != 0
                or receipt.get("is_mock") is not False
                or receipt.get("recovered_existing") is not True
                or Path(receipt.get("media_path", "")).resolve() != dest
            ):
                dest.unlink(missing_ok=True)
                raise ExistingVideoRecoveryError(
                    "Provider must return a real download-only receipt for this destination"
                )
            info = _inspect_trusted(dest, seconds)
            if info["sha256"] != receipt.get("source_sha256"):
                dest.unlink(missing_ok=True)
                raise ExistingVideoRecoveryError("Provider receipt hash does not match bytes")
        completed = complete_submitted_job(
            db, job_id, provider_task_id=row["provider_task_id"],
            result_sha256=info["sha256"], result_path=str(dest),
        )
        return {
            "job_id": job_id, "series_id": completed["series_id"],
            "file_id": row["file_id"], "mp4_path": str(dest),
            "source_sha256": info["sha256"], "cached": False,
            "new_model_generation_calls": 0,
            "vendor_charge_usd": None,
        }
    finally:
        with db.connection() as conn:
            conn.execute("BEGIN IMMEDIATE")
            conn.execute(
                "UPDATE google_existing_files SET recovery_active=0 WHERE job_id=?",
                (job_id,),
            )


def unlock_stale_google_recovery(
    db: Database, job_id: str, *, operator_reviewed: bool = False,
) -> None:
    """Manual-only crash recovery. Never resubmits a paid model request."""
    if operator_reviewed is not True:
        raise ExistingVideoRecoveryError("Explicit operator review required")
    with db.connection() as conn:
        conn.execute("BEGIN IMMEDIATE")
        row = _job_and_file(conn, job_id)
        _eligible(row)
        if not row["recovery_active"]:
            raise ExistingVideoRecoveryError("No recovery lock to clear")
        conn.execute(
            "UPDATE google_existing_files SET recovery_active=0 WHERE job_id=?",
            (job_id,),
        )
        _event(conn, job_id, "existing_google_download_unlocked",
               row["status"], row["status"], {"operator_reviewed": True})


def compose_recovered_google_shots(
    db: Database, production_id: str, media_root: Path,
) -> dict:
    """Recompose one episode from verified recovered shots; gaps remain previews."""
    with db.connection() as conn:
        rows = conn.execute(
            """SELECT j.*,g.file_id FROM shot_jobs j
               LEFT JOIN google_existing_files g ON g.job_id=j.id
               WHERE j.production_id=? AND j.provider='google'
               ORDER BY j.shot_id""", (production_id,),
        ).fetchall()
        if not rows:
            raise ExistingVideoRecoveryError("No Google shot jobs in production")
        media = {}
        for row in rows:
            if row["status"] != "succeeded":
                continue
            if row["file_id"] is None:
                raise ExistingVideoRecoveryError("Completed Google shot missing file binding")
            seconds = _duration(conn, row)
            path = _location(media_root, row)
            if Path(row["result_path"]).resolve() != path:
                raise ExistingVideoRecoveryError("Media scope mismatch")
            _inspect_trusted(path, seconds, expected_sha=row["result_sha256"])
            media[row["shot_id"]] = path
    # Only local FFmpeg compositing; no Google SDK, no model request.
    result = render_approved_preview(db, production_id, media_root, source_clips=media)
    result["reused_existing_google_shots"] = len(media)
    result["new_model_generation_calls"] = 0
    result["historical_vendor_charge_unverified"] = True
    # Persist the compositing handoff without rewriting the compositor's local
    # paid_api_calls=0 scope or inventing historical provider spend.
    output = Path(result["mp4_path"]).parent / "manifest.json"
    output.write_text(
        json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8",
    )
    return result
